// Translate a part of a pattern (a region or topic name); null if unknown
function esPart(text) { var out = toSpanish(text); return out === null ? null : out; }
function plural(n, one, many) { return Number(n) === 1 ? one : many; }
// Region names after "in" and "to" need an article in Spanish: "en el Sur de Florida", "al Sur de Florida"
var ES_REGION_ARTICLE = { 'South Florida': 'el', 'Central Florida': 'el', 'North Florida': 'el', 'Panhandle': 'el', 'The Keys': 'los', 'the Panhandle': 'el' };
function esIn(region) {
  var name = esPart(region);
  if (name === null) return null;
  var article = ES_REGION_ARTICLE[region];
  if (article === 'los') return 'en los ' + name.replace(/^Los /, '');
  return 'en ' + (article ? 'el ' : '') + name.replace(/^el /, '');
}
function esTo(region) {
  var place = esIn(region);
  return place === null ? null : place.replace(/^en el /, 'al ').replace(/^en /, 'a ');
}

